import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = resolve(root, "contracts/protocol-v4.json");
const check = process.argv.includes("--check");
const schema = JSON.parse(await readFile(schemaPath, "utf8"));

const allowedTypes = new Set([
  "string",
  "optionalString",
  "u64",
  "optionalU64",
  "bool",
  "json",
  "optionalJson",
  "stringArray",
]);
const names = new Set();
for (const message of schema.messages) {
  if (!message.name || !message.wireType || names.has(message.wireType)) {
    throw new Error(
      `invalid or duplicate protocol message: ${message.wireType}`,
    );
  }
  names.add(message.wireType);
  for (const field of [...schema.baseFields, ...message.fields]) {
    if (!allowedTypes.has(field.type)) {
      throw new Error(
        `unsupported field type ${field.type} on ${message.name}`,
      );
    }
  }
}

const pascal = (value) => value[0].toUpperCase() + value.slice(1);
const snake = (value) =>
  value
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/-/g, "_")
    .toLowerCase();
const optional = (type) => type.startsWith("optional");

const tsType = (type) =>
  ({
    string: "string",
    optionalString: "string",
    u64: "number",
    optionalU64: "number",
    bool: "boolean",
    json: "unknown",
    optionalJson: "unknown",
    stringArray: "string[]",
  })[type];

function generateTypeScript() {
  const interfaces = schema.messages
    .map((message) => {
      const fields = message.fields
        .map(
          (field) =>
            `  ${field.name}${optional(field.type) ? "?" : ""}: ${tsType(field.type)};`,
        )
        .join("\n");
      return `export interface ${message.name}Message extends ProtocolV4Envelope {\n  type: "${message.wireType}";\n${fields}\n}`;
    })
    .join("\n\n");
  const union = schema.messages
    .map(({ name }) => `${name}Message`)
    .join("\n  | ");
  return `// @generated by scripts/generate-protocol-v4.mjs — do not edit.\nexport const PROTOCOL_V4_VERSION = ${schema.protocolVersion} as const;\n\nexport interface ProtocolV4Envelope {\n  requestId: string;\n  sessionId: string;\n  protocolVersion: typeof PROTOCOL_V4_VERSION;\n}\n\n${interfaces}\n\nexport type ProtocolV4Message =\n  | ${union};\n`;
}

const rustType = (type) =>
  ({
    string: "String",
    optionalString: "Option<String>",
    u64: "u64",
    optionalU64: "Option<u64>",
    bool: "bool",
    json: "serde_json::Value",
    optionalJson: "Option<serde_json::Value>",
    stringArray: "Vec<String>",
  })[type];

function rustField(field) {
  const rustName = snake(field.name);
  const attributes = [];
  if (rustName !== field.name) attributes.push(`rename = "${field.name}"`);
  if (optional(field.type))
    attributes.push('skip_serializing_if = "Option::is_none"');
  const attribute = attributes.length
    ? `        #[serde(${attributes.join(", ")})]\n`
    : "";
  return `${attribute}        ${rustName}: ${rustType(field.type)},`;
}

function generateRust() {
  const variants = schema.messages
    .map((message) => {
      const fields = [...schema.baseFields, ...message.fields]
        .map(rustField)
        .join("\n");
      return `    #[serde(rename = "${message.wireType}")]\n    ${message.name} {\n${fields}\n    },`;
    })
    .join("\n\n");
  return `// @generated by scripts/generate-protocol-v4.mjs — do not edit.\nuse serde::{Deserialize, Serialize};\n\npub const PROTOCOL_V4_VERSION: u64 = ${schema.protocolVersion};\n\n#[derive(Debug, Clone, Serialize, Deserialize)]\n#[serde(tag = "type")]\npub enum ProtocolV4Message {\n${variants}\n}\n`;
}

const csharpType = (type) =>
  ({
    string: "string",
    optionalString: "string?",
    u64: "ulong",
    optionalU64: "ulong?",
    bool: "bool",
    json: "JsonElement",
    optionalJson: "JsonElement?",
    stringArray: "List<string>",
  })[type];

function csharpProperty(field) {
  const name = pascal(field.name);
  const type = csharpType(field.type);
  const initializer =
    field.type === "string"
      ? ' = "";'
      : field.type === "stringArray"
        ? " = new();"
        : "";
  const ignore = optional(field.type)
    ? "\n    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]"
    : "";
  return `    [JsonPropertyName("${field.name}")]${ignore}\n    public ${type} ${name} { get; set; }${initializer}`;
}

function generateCSharp() {
  const derived = schema.messages
    .map(
      (message) =>
        `[JsonDerivedType(typeof(${message.name}V4), "${message.wireType}")]`,
    )
    .join("\n");
  const classes = schema.messages
    .map((message) => {
      const fields = message.fields.map(csharpProperty).join("\n");
      return `public sealed class ${message.name}V4 : ProtocolV4Message\n{\n${fields}\n}`;
    })
    .join("\n\n");
  return `// <auto-generated by scripts/generate-protocol-v4.mjs />\n#nullable enable\nusing System.Collections.Generic;\nusing System.Text.Json;\nusing System.Text.Json.Serialization;\n\nnamespace ${schema.namespace};\n\npublic static class ProtocolV4\n{\n    public const ulong Version = ${schema.protocolVersion};\n}\n\n[JsonPolymorphic(TypeDiscriminatorPropertyName = "type")]\n${derived}\npublic abstract class ProtocolV4Message\n{\n    [JsonPropertyName("requestId")] public string RequestId { get; set; } = "";\n    [JsonPropertyName("sessionId")] public string SessionId { get; set; } = "";\n    [JsonPropertyName("protocolVersion")] public ulong ProtocolVersion { get; set; } = ProtocolV4.Version;\n}\n\n${classes}\n`;
}

const outputs = new Map([
  [resolve(root, "src/generated/protocol-v4.ts"), generateTypeScript()],
  [resolve(root, "src-tauri/src/generated/protocol_v4.rs"), generateRust()],
  [
    resolve(
      root,
      "apps/native-office/LaTeXSnipper.Shared/Generated/ProtocolV4.g.cs",
    ),
    generateCSharp(),
  ],
]);

for (const [path, content] of outputs) {
  if (check) {
    const current = await readFile(path, "utf8").catch(() => null);
    if (current !== content) {
      throw new Error(
        `${path.slice(root.length + 1)} is stale; run npm run protocol:generate`,
      );
    }
  } else {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content, "utf8");
    console.log(`generated ${path.slice(root.length + 1)}`);
  }
}
